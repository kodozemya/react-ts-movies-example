import { useEffect, useState } from "react";

/**
 * Віддає значення із затримкою: поки воно змінюється, хук мовчить,
 * і повертає його аж тоді, коли зміни припинилися на `delay` мілісекунд.
 *
 * `<T>` тут робить справжню роботу: хук повертає рівно той тип, що йому
 * дали. Для рядка — `string`, для об'єкта фільтрів — тип цього об'єкта.
 * Без тип-параметра назовні виходив би `unknown` або `any`.
 *
 * Навіщо взагалі. У макеті пошук — це поле без кнопки: результати мають
 * з'являтися під час набору. Але запит на кожну літеру означає сім запитів
 * на слово «месники» — і швидке вичерпання ліміту TMDB.
 */
export function useDebounced<T>(value: T, delay = 400): T {
  const [settled, setSettled] = useState<T>(value);

  useEffect(() => {
    const timer = setTimeout(() => setSettled(value), delay);

    /*
      React викликає цю функцію перед наступним запуском ефекту — тобто
      на кожній новій літері таймер скасовується й заводиться заново.
      Спрацює лише останній. Без clearTimeout дебаунсу не було б узагалі.
    */
    return () => clearTimeout(timer);
  }, [value, delay]);

  return settled;
}
